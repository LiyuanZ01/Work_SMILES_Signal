def sha256(path: Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1024 * 1024), b""):
            h.update(chunk)
    return h.hexdigest()


def quarters() -> pd.Index:
    return pd.period_range(SAMPLE_START, SAMPLE_END, freq="Q").astype(str)


def read_wto_csv_zip(path: Path) -> tuple[pd.DataFrame, str, str]:
    with zipfile.ZipFile(path) as archive:
        names = [n for n in archive.namelist() if n.lower().endswith(".csv")]
        if len(names) != 1:
            raise RuntimeError(f"Expected one CSV in {path}, found {names}")
        raw = archive.read(names[0])
    encoding = None
    frame = None
    for candidate in ["utf-8-sig", "cp1252", "latin1"]:
        try:
            from io import BytesIO
            frame = pd.read_csv(BytesIO(raw), encoding=candidate)
            encoding = candidate
            break
        except UnicodeDecodeError:
            continue
    if frame is None or encoding is None:
        raise RuntimeError(f"Unable to decode {path}")
    return frame, names[0], encoding


def official_raw_files() -> tuple[pd.DataFrame, pd.DataFrame, dict[str, Any]]:
    export_zip = EXPORT_DIR / "china_export_official_portal_csv.zip"
    import_zip = EXPORT_DIR / "partner_imports_official_portal_csv.zip"
    if not export_zip.exists() or not import_zip.exists():
        raise FileNotFoundError(f"Missing exact WTO portal exports in {EXPORT_DIR}")
    export, export_member, export_encoding = read_wto_csv_zip(export_zip)
    imports, import_member, import_encoding = read_wto_csv_zip(import_zip)
    required = [
        "Indicator Code", "Reporting Economy ISO3A Code", "Reporting Economy",
        "Period Code", "Year", "Value",
    ]
    for name, frame in [("export", export), ("imports", imports)]:
        missing = [c for c in required if c not in frame.columns]
        if missing:
            raise RuntimeError(f"{name} WTO export missing columns {missing}")
        frame["quarter"] = frame["Year"].astype(int).astype(str) + frame["Period Code"].astype(str)
        frame["Value"] = pd.to_numeric(frame["Value"], errors="coerce")
    export = export[
        export["Indicator Code"].eq("ITS_MTP_QXVSA")
        & export["Reporting Economy ISO3A Code"].eq("CHN")
    ].copy()
    imports = imports[imports["Indicator Code"].eq("ITS_MTP_QMVSA")].copy()
    q = set(quarters())
    export = export[export["quarter"].isin(q)].drop_duplicates("quarter", keep="last")
    imports = imports[imports["quarter"].isin(q)].drop_duplicates(
        ["quarter", "Reporting Economy ISO3A Code"], keep="last"
    )
    export_long = export[["quarter", "Value"]].rename(columns={"Value": "value"})
    export_long["alpha3"] = "CHN"
    export_long["economy"] = "China"
    export_long["flow"] = "export"
    export_long["dataset"] = "ITS_MTP_QXVSA"
    export_long["series_code"] = "WTO_STATS_PORTAL_DIRECT"
    export_long["source_url"] = "https://stats.wto.org/en"
    export_long["source_file"] = export_zip.name
    import_long = imports[[
        "quarter", "Value", "Reporting Economy ISO3A Code", "Reporting Economy"
    ]].rename(columns={
        "Value": "value",
        "Reporting Economy ISO3A Code": "alpha3",
        "Reporting Economy": "economy",
    })
    import_long["flow"] = "import"
    import_long["dataset"] = "ITS_MTP_QMVSA"
    import_long["series_code"] = "WTO_STATS_PORTAL_DIRECT"
    import_long["source_url"] = "https://stats.wto.org/en"
    import_long["source_file"] = import_zip.name
    selected = sorted(FIXED_WEIGHTS)
    present = sorted(import_long["alpha3"].dropna().unique().tolist())
    for code in sorted(set(selected) - set(present)):
        missing_rows = pd.DataFrame({
            "quarter": quarters(), "value": np.nan, "alpha3": code,
            "economy": "United Arab Emirates" if code == "ARE" else code,
            "flow": "import", "dataset": "ITS_MTP_QMVSA",
            "series_code": "WTO_STATS_PORTAL_DIRECT_NO_RECORDS",
            "source_url": "https://stats.wto.org/en", "source_file": import_zip.name,
        })
        import_long = pd.concat([import_long, missing_rows], ignore_index=True)
    import_long["source_status"] = np.where(import_long["value"].notna(), "available", "unavailable")
    export_long = export_long.sort_values("quarter").reset_index(drop=True)
    import_long = import_long.sort_values(["alpha3", "quarter"]).reset_index(drop=True)
    audit = {
        "export_zip": export_zip.name,
        "export_zip_sha256": sha256(export_zip),
        "export_member": export_member,
        "export_encoding": export_encoding,
        "import_zip": import_zip.name,
        "import_zip_sha256": sha256(import_zip),
        "import_member": import_member,
        "import_encoding": import_encoding,
        "china_quarters": int(export_long["value"].notna().sum()),
        "selected_partner_count": len(selected),
        "available_partner_count": int(import_long.loc[import_long["value"].notna(), "alpha3"].nunique()),
        "unavailable_partners": sorted(set(selected) - set(present)),
    }
    return export_long, import_long, audit


def weighted_index(wide: pd.DataFrame, weights_by_quarter: Iterable[pd.Series]) -> pd.DataFrame:
    rows = []
    for quarter, weights in zip(quarters(), weights_by_quarter):
        values = wide.loc[quarter].reindex(weights.index)
        valid = values.notna() & weights.notna() & weights.gt(0)
        coverage = float(weights[valid].sum())
        index = float((values[valid] * weights[valid]).sum() / coverage) if coverage > 0 else np.nan
        rows.append({
            "quarter": quarter, "index": index, "coverage": coverage,
            "market_count": int(valid.sum()),
        })
    return pd.DataFrame(rows)


def build_model_data(exports: pd.DataFrame, imports: pd.DataFrame) -> tuple[pd.DataFrame, pd.DataFrame]:
    q = list(quarters())
    wide = imports.pivot(index="quarter", columns="alpha3", values="value").reindex(q)
    fixed = pd.Series(FIXED_WEIGHTS, dtype=float)
    fixed_index = weighted_index(wide, [fixed for _ in q]).rename(columns={
        "index": "fixed_external_demand_index",
        "coverage": "fixed_coverage",
        "market_count": "fixed_market_count",
    })
    rolling = pd.read_csv(BASE_DIR / "rolling_weights_top20_2005_2024.csv")
    rolling_map = rolling.pivot(
        index="sample_year", columns="alpha3", values="rolling_weight_ex_hk_mac"
    )
    rolling_weights = [rolling_map.loc[int(x[:4])].dropna().astype(float) for x in q]
    rolling_index = weighted_index(wide, rolling_weights).rename(columns={
        "index": "rolling_external_demand_index",
        "coverage": "rolling_coverage",
        "market_count": "rolling_market_count",
    })
    reer = pd.read_csv(BASE_DIR / "china_reer_quarterly.csv")
    model = pd.DataFrame({"quarter": q})
    model["year"] = model["quarter"].str[:4].astype(int)
    model["wto_export_index"] = exports.set_index("quarter")["value"].reindex(q).to_numpy()
    model = model.merge(fixed_index, on="quarter", how="left")
    model = model.merge(rolling_index, on="quarter", how="left")
    model = model.merge(reer[["quarter", "reer_index", "reer_qoq"]], on="quarter", how="left")
    model["export_qoq"] = model["wto_export_index"].pct_change(fill_method=None) * 100
    model["export_yoy"] = model["wto_export_index"].pct_change(4, fill_method=None) * 100
    model["fixed_demand_qoq"] = model["fixed_external_demand_index"].pct_change(fill_method=None) * 100
    model["rolling_demand_qoq"] = model["rolling_external_demand_index"].pct_change(fill_method=None) * 100
    model["export_qoq_lag1"] = model["export_qoq"].shift(1)
    model["fixed_demand_lag1"] = model["fixed_demand_qoq"].shift(1)
    model["rolling_demand_lag1"] = model["rolling_demand_qoq"].shift(1)
    for lag in range(2, 5):
        model[f"fixed_demand_lag{lag}"] = model["fixed_demand_qoq"].shift(lag)
    model["reer_lag1"] = model["reer_qoq"].shift(1)
    model["post2018"] = model["year"].ge(2018).astype(int)
    model["dummy_2020q1"] = model["quarter"].eq("2020Q1").astype(int)
    model["dummy_2020q2"] = model["quarter"].eq("2020Q2").astype(int)
    model["fixed_demand_x_post2018"] = model["fixed_demand_qoq"] * model["post2018"]
    model["fixed_model_eligible"] = model["fixed_coverage"].ge(COVERAGE_THRESHOLD)
    model["rolling_model_eligible"] = model["rolling_coverage"].ge(COVERAGE_THRESHOLD)
    coverage = model[[
        "quarter", "fixed_coverage", "fixed_market_count", "rolling_coverage",
        "rolling_market_count", "fixed_model_eligible", "rolling_model_eligible",
    ]].copy()
    return model, coverage


def fit_hac(data: pd.DataFrame, name: str, regressors: list[str], exclude_2020: bool = False,
            threshold_rolling: bool = False) -> tuple[pd.DataFrame, dict[str, Any]]:
    frame = data.copy()
    if exclude_2020:
        frame = frame[~frame["year"].eq(2020)].copy()
    if threshold_rolling:
        frame = frame[frame["rolling_model_eligible"]].copy()
    frame = frame.dropna(subset=["export_qoq", *regressors]).copy()
    x = sm.add_constant(frame[regressors], has_constant="add")
    fit = sm.OLS(frame["export_qoq"], x).fit(
        cov_type="HAC", cov_kwds={"maxlags": HAC_LAGS, "use_correction": True}, use_t=True
    )
    conf = fit.conf_int()
    rows = []
    for parameter in fit.params.index:
        rows.append({
            "model": name, "dependent": "export_qoq", "parameter": parameter,
            "coefficient": float(fit.params[parameter]),
            "std_error_hac4": float(fit.bse[parameter]),
            "t_stat": float(fit.tvalues[parameter]),
            "p_value": float(fit.pvalues[parameter]),
            "ci_low_95": float(conf.loc[parameter, 0]),
            "ci_high_95": float(conf.loc[parameter, 1]),
            "n": int(fit.nobs), "r_squared": float(fit.rsquared),
            "adjusted_r_squared": float(fit.rsquared_adj),
            "durbin_watson": float(durbin_watson(fit.resid)),
            "sample_start": frame["quarter"].iloc[0], "sample_end": frame["quarter"].iloc[-1],
            "covariance": "HAC(4), finite-sample correction, t reference",
        })
    summary: dict[str, Any] = {
        "model": name, "status": "estimated", "dependent": "export_qoq",
        "regressors": regressors, "n": int(fit.nobs), "r_squared": float(fit.rsquared),
        "adjusted_r_squared": float(fit.rsquared_adj),
        "durbin_watson": float(durbin_watson(fit.resid)),
        "sample_start": frame["quarter"].iloc[0], "sample_end": frame["quarter"].iloc[-1],
    }
    if {"fixed_demand_qoq", "fixed_demand_lag1"}.issubset(fit.params.index):
        cov = fit.cov_params()
        effect = float(fit.params["fixed_demand_qoq"] + fit.params["fixed_demand_lag1"])
        variance = (
            cov.loc["fixed_demand_qoq", "fixed_demand_qoq"]
            + cov.loc["fixed_demand_lag1", "fixed_demand_lag1"]
            + 2 * cov.loc["fixed_demand_qoq", "fixed_demand_lag1"]
        )
        se = math.sqrt(max(float(variance), 0.0))
        t = effect / se if se else np.nan
        p = float(2 * stats.t.sf(abs(t), fit.df_resid)) if np.isfinite(t) else np.nan
        summary.update({
            "current_plus_lag1_effect": effect, "current_plus_lag1_se": se,
            "current_plus_lag1_p_value": p,
            "effect_interpretation": "two-quarter conditional association; not a causal elasticity",
        })
    return pd.DataFrame(rows), summary


def estimate_models(model: pd.DataFrame) -> tuple[pd.DataFrame, list[dict[str, Any]]]:
    specs = [
        ("M_fixed_baseline", ["fixed_demand_qoq", "fixed_demand_lag1", "reer_lag1", "export_qoq_lag1", "dummy_2020q1", "dummy_2020q2"], False, False),
        ("M_rolling_threshold70", ["rolling_demand_qoq", "rolling_demand_lag1", "reer_lag1", "export_qoq_lag1", "dummy_2020q1", "dummy_2020q2"], False, True),
        ("M_fixed_lag1_only", ["fixed_demand_lag1", "reer_lag1", "export_qoq_lag1", "dummy_2020q1", "dummy_2020q2"], False, False),
        ("M_fixed_lags1_4", ["fixed_demand_lag1", "fixed_demand_lag2", "fixed_demand_lag3", "fixed_demand_lag4", "reer_lag1", "export_qoq_lag1", "dummy_2020q1", "dummy_2020q2"], False, False),
        ("M_fixed_exclude2020", ["fixed_demand_qoq", "fixed_demand_lag1", "reer_lag1", "export_qoq_lag1"], True, False),
        ("M_fixed_post2018", ["fixed_demand_qoq", "fixed_demand_lag1", "reer_lag1", "export_qoq_lag1", "post2018", "fixed_demand_x_post2018", "dummy_2020q1", "dummy_2020q2"], False, False),
        ("M_rolling_baseline", ["rolling_demand_qoq", "rolling_demand_lag1", "reer_lag1", "export_qoq_lag1", "dummy_2020q1", "dummy_2020q2"], False, False),
    ]
    rows = []; summaries = []
    for name, regs, exclude, threshold in specs:
        result, summary = fit_hac(model, name, regs, exclude, threshold)
        rows.append(result); summaries.append(summary)
    return pd.concat(rows, ignore_index=True), summaries


def main() -> int:
    exports, imports, source_audit = official_raw_files()
    model, coverage = build_model_data(exports, imports)
    estimates, summaries = estimate_models(model)
    exports.to_csv(OUT / "wto_china_export_volume.csv", index=False)
    imports.to_csv(OUT / "wto_partner_import_volume.csv", index=False)
    model.to_csv(OUT / "v15_model_data.csv", index=False)
    coverage.to_csv(OUT / "v15_coverage_audit.csv", index=False)
    estimates.to_csv(OUT / "v15_export_models.csv", index=False)
    (OUT / "v15_model_summaries.json").write_text(json.dumps(summaries, indent=2), encoding="utf-8")
    table2 = estimates[estimates["parameter"].ne("const")][[
        "model", "parameter", "coefficient", "std_error_hac4", "p_value", "n",
        "r_squared", "sample_start", "sample_end",
    ]]
    table2.to_csv(OUT / "Table2_WTO_export_models.csv", index=False)
    # Retain frozen inputs used in the rebuild.
    for name in [
        "rolling_weights_top20_2005_2024.csv", "china_reer_quarterly.csv",
        "reconstructed_fixed_weights_all_markets.csv", "mirror_imports_from_china_panel.csv",
    ]:
        source = BASE_DIR / name
        if source.exists():
            shutil.copy2(source, OUT / name)
    status = {
        "status": "complete", "generated_at_utc": datetime.now(timezone.utc).isoformat(),
        "source": "direct public WTO Stats portal CSV exports",
        "source_audit": source_audit,
        "sample": [SAMPLE_START, SAMPLE_END],
        "china_complete": bool(exports["value"].notna().sum() == 80),
        "available_partner_count": int(imports.loc[imports["value"].notna(), "alpha3"].nunique()),
        "fixed_coverage": {
            "mean": float(model["fixed_coverage"].mean()),
            "min": float(model["fixed_coverage"].min()),
            "max": float(model["fixed_coverage"].max()),
        },
        "software": {"pandas": pd.__version__, "numpy": np.__version__, "scipy": scipy.__version__, "statsmodels": statsmodels.__version__},
        "limitations": [
            "The United Arab Emirates returned no observations and remains missing.",
            "The WTO portal data are a current vintage and can differ from earlier mirrored vintages because of precision and revisions.",
            "Coefficients are conditional associations, not causal elasticities.",
        ],
    }
    (OUT / "v15_status.json").write_text(json.dumps(status, indent=2), encoding="utf-8")
    manifest = {
        "generated_at_utc": datetime.now(timezone.utc).isoformat(),
        "files": {p.name: {"bytes": p.stat().st_size, "sha256": sha256(p)} for p in OUT.glob("*") if p.is_file()},
        "source_audit": source_audit,
    }
    (OUT / "v15_manifest.json").write_text(json.dumps(manifest, indent=2), encoding="utf-8")
    print(json.dumps(status, indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
