#!/usr/bin/env python3
"""Rebuild the v15 model dataset from direct WTO Stats portal exports.

Inputs:
- exact WTO portal CSV ZIPs created by export_wto_stats_selected_series.py;
- rolling weights and REER files generated by the frozen v15 replication.

Outputs use the same filenames and column schema as the frozen v15 results so
that the existing P1 and P2 audit programs can run unchanged. The UAE remains
missing because the portal returns no observations; it is never replaced by
zero. Fixed and rolling indices are renormalized over available positive-weight
markets exactly as in the frozen model.
"""
from __future__ import annotations

