from datetime import datetime, timezone
from pathlib import Path
from typing import Any, Iterable

import numpy as np
import pandas as pd
import scipy
import statsmodels
import statsmodels.api as sm
from scipy import stats
from statsmodels.stats.stattools import durbin_watson

SAMPLE_START = "2005Q1"
SAMPLE_END = "2024Q4"
HAC_LAGS = 4
COVERAGE_THRESHOLD = 0.70
BASE_DIR = Path(os.environ.get("BASE_RESULTS_DIR", "external_demand_wto/results"))
EXPORT_DIR = Path(os.environ.get("OFFICIAL_EXPORT_DIR", "external_demand_wto/wto_exact_export"))
OUT = Path(os.environ.get("OFFICIAL_OUTPUT_DIR", "external_demand_wto/official_results"))
OUT.mkdir(parents=True, exist_ok=True)

